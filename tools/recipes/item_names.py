#!/usr/bin/env python3
"""Write the search corpus's item-name overlay (data/corpus/names/items.tsv) from the recipe database.

The recipe database holds every item's in-game display name as our own pack renders it, so it beats every other
source tools/gtnh-search has (lang files, GregTech's source tables): it covers items whose names are computed in code,
like GregGuns' GregTech machines. One line per item: `registry<TAB>meta<TAB>name`.

  item_names.py [--db data/recipes.sqlite] [--out data/corpus/names/items.tsv]

Names that are still unlocalized keys (`itemFoo.name`) are left out so the other sources can try; formatting codes
(the section sign plus one character) are stripped. Standard library only.
"""
import argparse, os, re, sqlite3, sys
from pathlib import Path

ROOT = Path(os.environ.get("DAVE_AGENT_ROOT") or Path(__file__).resolve().parent.parent.parent)
FORMAT = re.compile("§.")
UNLOCALIZED = re.compile(r"[\w.:-]+\.name")


def rows(db):
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    try:
        for reg, meta, name in con.execute(
                "SELECT registry, meta, name FROM items WHERE kind = 'item' AND registry IS NOT NULL "
                "AND name IS NOT NULL ORDER BY registry, meta"):
            name = " ".join(FORMAT.sub("", name).split())
            if not name or UNLOCALIZED.fullmatch(name) or "\t" in reg:
                continue
            yield reg, 0 if meta is None else meta, name
    finally:
        con.close()


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--db", type=Path, default=ROOT / "data" / "recipes.sqlite")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "corpus" / "names" / "items.tsv")
    a = ap.parse_args(argv)
    if not a.db.is_file():
        print(f"item_names: no recipe database at {a.db}", file=sys.stderr)
        return 1
    seen, lines = set(), ["# registry\tmeta\tname -- generated by tools/recipes/item_names.py from the recipe database"]
    for reg, meta, name in rows(a.db):
        if (reg, meta) not in seen:
            seen.add((reg, meta))
            lines.append(f"{reg}\t{meta}\t{name}")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = a.out.with_name(a.out.name + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, a.out)
    print(f"item_names: {len(seen)} names -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
